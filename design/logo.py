"""Generates every Herewise logo asset from one set of numbers. Run: `python design/logo.py`.

The mark is a letter H whose crossbar is a tick. The one rule that matters: the rise of the tick stops
at 44 per cent of the height and never reaches the top of the right stem. An earlier draft let it run
up to the stem and the icon read as a Cyrillic "и" at 16 px.

Everything is drawn on a 64 unit grid, so a 16 px icon puts every edge on a whole pixel (64 / 16 = 4)
and 32, 48 and 256 divide cleanly too. 16 and 24 are still drawn separately, by hand, below: at those
sizes a scaled copy turns the tick into grey mush.

Colours come from design/tokens.css, which is generated by design/palette.py. Nothing here invents one.
"""
from __future__ import annotations

import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
OUT = HERE / "logo"
# The app serves its own copies. Written from here rather than copied by hand, so "never edit an
# exported asset" holds for the ones the screens actually load.
APP_OUT = HERE.parent / "rollcall" / "static" / "img"
APP_ASSETS = ["herewise-mark.svg", "herewise-lockup.svg"]

# -- the grid ---------------------------------------------------------------------------------------

BOX = 64
STEM_W = 8
LEFT_X = 12          # left stem spans 12..20, centre 16
RIGHT_X = 44         # right stem spans 44..52, centre 48
TOP_Y = 8
BOTTOM_Y = 56
TICK_W = 6
# Start on the left stem, drop steeply to the vertex, then rise long and shallow into the right stem.
# The short steep arm is what makes it read as a tick rather than a sagging crossbar: the first draft
# used a shallow left arm and read as a wide V lying down at every size.
# The rise stops at y=24 of 64, leaving a quarter of the height as clear stem above it. That cap is the
# other half of the design: a tick reaching the top of the right stem turns the icon into a Cyrillic "и".
TICK = [(15, 31), (24, 40), (49, 24)]

PADDING = 6          # clear space around the mark, in grid units, for the padded variants


def _tokens() -> dict:
    return json.loads((HERE / "tokens.json").read_text(encoding="utf-8"))["colour"]


def colours(theme: str = "light") -> dict:
    t = _tokens()[theme]
    return {"paper": t["paper"], "ink": t["ink"], "accent": t["accent"]}


# -- SVG --------------------------------------------------------------------------------------------

def mark_svg(themed: bool = True) -> str:
    """The scalable mark.

    `themed` writes the stems as `currentColor` and the tick as `var(--hw-accent)`, so a screen that
    has loaded tokens.css gets the right colours in light and dark without a second file. The
    standalone variant hard-codes the light values for anything outside the app, such as an installer.
    """
    light = colours("light")
    ink = "currentColor" if themed else light["ink"]
    accent = f"var(--hw-accent, {light['accent']})" if themed else light["accent"]
    points = " ".join(f"{x} {y}" for x, y in TICK)
    return f'''<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {BOX} {BOX}" width="{BOX}" height="{BOX}"
     role="img" aria-label="Herewise">
  <title>Herewise</title>
  <rect x="{LEFT_X}" y="{TOP_Y}" width="{STEM_W}" height="{BOTTOM_Y - TOP_Y}" fill="{ink}"/>
  <rect x="{RIGHT_X}" y="{TOP_Y}" width="{STEM_W}" height="{BOTTOM_Y - TOP_Y}" fill="{ink}"/>
  <polyline points="{points}" fill="none" stroke="{accent}" stroke-width="{TICK_W}"
            stroke-linecap="round" stroke-linejoin="round"/>
</svg>
'''


def tile_svg() -> str:
    """The mark on its own paper tile, for an installer, a shortcut or a favicon source."""
    light = colours("light")
    inner = BOX - 2 * PADDING
    scale = inner / BOX
    points = " ".join(f"{x} {y}" for x, y in TICK)
    return f'''<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {BOX} {BOX}" width="{BOX}" height="{BOX}"
     role="img" aria-label="Herewise">
  <title>Herewise</title>
  <rect width="{BOX}" height="{BOX}" rx="12" fill="{light['paper']}"/>
  <g transform="translate({PADDING} {PADDING}) scale({scale:.4f})">
    <rect x="{LEFT_X}" y="{TOP_Y}" width="{STEM_W}" height="{BOTTOM_Y - TOP_Y}" fill="{light['ink']}"/>
    <rect x="{RIGHT_X}" y="{TOP_Y}" width="{STEM_W}" height="{BOTTOM_Y - TOP_Y}" fill="{light['ink']}"/>
    <polyline points="{points}" fill="none" stroke="{light['accent']}" stroke-width="{TICK_W}"
              stroke-linecap="round" stroke-linejoin="round"/>
  </g>
</svg>
'''


def lockup_svg() -> str:
    """Mark plus wordmark.

    The wordmark is set in type, not drawn: `herewise` in Inter 600, lowercase, tracking -0.02em. It is
    left as live text on purpose, so it stays selectable and never drifts from the app's own type. A
    viewer without Inter falls back down the stack rather than showing a broken drawing.
    """
    light = colours("light")
    points = " ".join(f"{x} {y}" for x, y in TICK)
    return f'''<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 260 64" width="260" height="64"
     role="img" aria-label="Herewise">
  <title>Herewise</title>
  <rect x="{LEFT_X}" y="{TOP_Y}" width="{STEM_W}" height="{BOTTOM_Y - TOP_Y}" fill="currentColor"/>
  <rect x="{RIGHT_X}" y="{TOP_Y}" width="{STEM_W}" height="{BOTTOM_Y - TOP_Y}" fill="currentColor"/>
  <polyline points="{points}" fill="none" stroke="var(--hw-accent, {light['accent']})"
            stroke-width="{TICK_W}" stroke-linecap="round" stroke-linejoin="round"/>
  <text x="76" y="43" fill="currentColor"
        font-family="Inter, 'Segoe UI', system-ui, sans-serif" font-size="34" font-weight="600"
        letter-spacing="-0.7">herewise</text>
</svg>
'''


# -- PNG --------------------------------------------------------------------------------------------

def _draw(size: int, theme: str, padded: bool):
    from PIL import Image, ImageDraw

    c = colours(theme)
    ss = 8  # supersample, then reduce: the tick has diagonals and needs the smoothing
    img = Image.new("RGBA", (size * ss, size * ss), c["paper"] if padded else (0, 0, 0, 0))
    d = ImageDraw.Draw(img)
    inner = (size - 2 * (PADDING * size / BOX)) if padded else size
    offset = (size - inner) / 2
    k = inner * ss / BOX

    def px(x, y):
        return (offset * ss + x * k, offset * ss + y * k)

    d.rectangle([px(LEFT_X, TOP_Y), px(LEFT_X + STEM_W, BOTTOM_Y)], fill=c["ink"])
    d.rectangle([px(RIGHT_X, TOP_Y), px(RIGHT_X + STEM_W, BOTTOM_Y)], fill=c["ink"])
    d.line([px(*p) for p in TICK], fill=c["accent"], width=max(1, round(TICK_W * k)), joint="curve")
    # round the tick's ends, which is what stroke-linecap does in the SVG
    r = TICK_W * k / 2
    for x, y in (TICK[0], TICK[-1]):
        cx, cy = px(x, y)
        d.ellipse([cx - r, cy - r, cx + r, cy + r], fill=c["accent"])
    return img.resize((size, size), Image.LANCZOS)


def _draw_small(size: int, theme: str):
    """16 and 24 px, drawn by hand on the pixel grid.

    At these sizes the test is the silhouette, not the detail: an H with a mark across it. Scaling the
    64 unit drawing down puts every edge on a half pixel and the whole thing turns to grey.
    """
    from PIL import Image, ImageDraw

    c = colours(theme)
    img = Image.new("RGBA", (size, size), (0, 0, 0, 0))
    d = ImageDraw.Draw(img)
    if size == 16:
        stem, top, bottom = 2, 2, 13
        left, right = 3, 11
        tick = [(4, 7), (6, 10), (12, 5)]
        tick_w = 2
    else:  # 24
        stem, top, bottom = 3, 3, 20
        left, right = 4, 17
        tick = [(6, 11), (9, 15), (18, 8)]
        tick_w = 3
    d.rectangle([left, top, left + stem - 1, bottom], fill=c["ink"])
    d.rectangle([right, top, right + stem - 1, bottom], fill=c["ink"])
    d.line(tick, fill=c["accent"], width=tick_w, joint="curve")
    return img


def png(size: int, theme: str = "light", padded: bool = False):
    if size in (16, 24) and not padded:
        return _draw_small(size, theme)
    return _draw(size, theme, padded)


# -- writing ----------------------------------------------------------------------------------------

SIZES = [16, 24, 32, 48, 64, 128, 256, 512]


def write() -> list[Path]:
    OUT.mkdir(parents=True, exist_ok=True)
    written = []

    for name, body in (("herewise-mark.svg", mark_svg(themed=True)),
                       ("herewise-mark-static.svg", mark_svg(themed=False)),
                       ("herewise-tile.svg", tile_svg()),
                       ("herewise-lockup.svg", lockup_svg())):
        (OUT / name).write_text(body, encoding="utf-8")
        written.append(OUT / name)

    for theme in ("light", "dark"):
        for size in SIZES:
            path = OUT / f"herewise-mark-{size}{'' if theme == 'light' else '-dark'}.png"
            png(size, theme).save(path)
            written.append(path)

    for size in (256, 512):
        path = OUT / f"herewise-tile-{size}.png"
        png(size, "light", padded=True).save(path)
        written.append(path)

    ico = OUT / "herewise.ico"
    png(256, "light", padded=True).save(ico, sizes=[(16, 16), (24, 24), (32, 32), (48, 48), (64, 64), (256, 256)])
    written.append(ico)

    APP_OUT.mkdir(parents=True, exist_ok=True)
    for name in APP_ASSETS:
        (APP_OUT / name).write_text((OUT / name).read_text(encoding="utf-8"), encoding="utf-8")
        written.append(APP_OUT / name)
    # The browser tab and the packaged window use the same icon file as the installer.
    (APP_OUT / "herewise.ico").write_bytes(ico.read_bytes())
    written.append(APP_OUT / "herewise.ico")
    return written


def contact_sheet(path: Path):
    """Every size, light and dark, actual size beside a magnified copy, on one image to be looked at.

    Cells are sized from the largest magnified icon, because the first version fixed them at 150 px and
    the 48 and 64 px icons ran straight over their neighbours.
    """
    from PIL import Image, ImageDraw

    shown = [16, 24, 32, 48, 64]
    zoom = 3
    cell = max(shown) * zoom + 40
    width = 30 + len(shown) * cell
    row_h = max(shown) * zoom + 60
    sheet = Image.new("RGB", (width, row_h * 2), "#FFFFFF")
    d = ImageDraw.Draw(sheet)
    for row, (theme, bg, label) in enumerate((("light", "#F9F6F2", "#221D17"),
                                              ("dark", "#15120F", "#EFEBE4"))):
        top = row * row_h
        d.rectangle([0, top, width, top + row_h], fill=bg)
        for col, size in enumerate(shown):
            x = 20 + col * cell
            img = png(size, theme)
            big = img.resize((size * zoom, size * zoom), Image.NEAREST)
            sheet.paste(big, (x, top + 30), big)
            sheet.paste(img, (x + size * zoom + 14, top + 30 + size * zoom - size), img)
            d.text((x, top + 10), f"{size} px", fill=label)
    sheet.save(path)
    return path


if __name__ == "__main__":
    files = write()
    print(f"wrote {len(files)} files to {OUT}")
    print("contact sheet:", contact_sheet(OUT / "contact-sheet.png"))
